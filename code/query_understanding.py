def detect_question_type(question: str) -> tuple[str, str]:  # 定义问题分类函数，返回问题类型和原因。
    if any(keyword in question for keyword in ["公式", "怎么算", "怎么计算", "计算公式", "挣值", "EV", "PV", "AC", "CPI", "SPI", "CV", "SV"]):  # 公式题必须有明确公式、计算动作或指标信号，避免把“云计算”误判成公式题。
        return "公式计算", "命中公式、计算或挣值指标关键词"  # 返回公式计算类型。
    if "ITTO" in question or "ITO" in question or "工具与技术" in question or ("输入" in question and "输出" in question) or ("工具" in question and "有哪些" in question):  # 只有明确出现 ITTO 结构或询问工具清单时才判定为输入输出工具技术题。
        return "输入输出工具技术", "命中输入、输出、工具与技术结构"  # 返回 ITTO 类型。
    if any(keyword in question for keyword in ["区别", "不同", "差异", "对比", "比较", "异同", "关系"]):  # 对比题使用明确比较词，不再把普通“和”当成对比题。
        return "区别对比", "命中比较、区别或关系关键词"  # 返回区别对比类型。
    if any(keyword in question for keyword in ["本章复习", "章节复习", "复习本章", "本章总结", "知识框架", "章节重点"]):  # 明确要求按章节梳理时，使用专门的章节复习模板。
        return "章节复习", "命中章节复习或知识框架关键词"  # 返回章节复习类型。
    list_question = any(keyword in question for keyword in ["有哪些", "包括哪些", "主要内容", "组成", "组成部分", "模式", "方法", "类型", "分类", "层次", "角色", "特点"])  # 先判断当前问题是否明显是在请求一个知识清单。
    process_question = any(keyword in question for keyword in ["步骤", "怎么做", "如何做", "如何", "顺序", "划分", "主要工作", "主要过程", "主要做什么", "过程包括", "阶段主要包括"])  # 识别动作、阶段和实施方式问题。
    if "工作流程" in question or process_question or ("流程" in question and not list_question) or ("过程" in question and not list_question):  # 流程题使用明确动作和阶段词识别；纯列表问题优先按考点归纳处理。
        return "流程步骤", "命中流程、步骤或阶段关键词"  # 返回流程步骤类型。
    if any(keyword in question for keyword in ["考点", "重点", "容易考", "记忆", "原则", "内容", "组成", "组成部分", "模式", "类型", "分类", "层次", "角色", "特点", "工具", "方法", "有哪些", "哪些", "包括哪些"]):  # 归纳题使用考点、列表和知识结构词识别。
        return "考点记忆", "命中考点、内容或列表关键词"  # 返回考点记忆类型。
    if any(keyword in question for keyword in ["什么是", "是什么", "概念", "定义", "含义", "是指", "主要解决什么问题"]):  # 定义题使用定义表达和作用边界识别。
        return "定义解释", "命中定义或概念关键词"  # 返回定义解释类型。
    if any(keyword in question for keyword in ["作用", "特征"]):  # 作用和特征通常要求解释一个概念的属性。
        return "定义解释", "命中作用或特征关键词"  # 返回定义解释类型。
    return "泛化查询", "未命中特定规则，按普通检索处理"  # 如果没有命中任何规则，就返回泛化查询。


def expand_query(question: str, question_type: str) -> str:  # 定义检索 query 增强函数。
    extra_words = EXPANSION_WORDS.get(question_type, [])  # 根据问题类型取出增强词。
    alias_words: list[str] = []  # 准备术语同义词列表。
    for term, aliases in TERM_ALIASES.items():  # 遍历每个术语映射。
        if term in question:  # 如果用户问题中出现这个术语。
            alias_words.extend(aliases)  # 就把对应同义词加入增强词。
    if not extra_words and not alias_words:  # 如果没有任何增强词。
        return question  # 直接返回原问题。
    extra = " ".join(extra_words + alias_words)  # 把类型增强词和术语同义词拼成字符串。
    return f"{question} {extra}"  # 返回“原问题 + 增强词”的检索 query。


def understand_query(question: str) -> QueryUnderstanding:  # 定义对外使用的问题理解函数。
    question = question.strip()  # 去掉问题首尾空白，避免空格影响规则判断。
    question_type, reason = detect_question_type(question)  # 调用分类函数，得到问题类型和原因。
    expanded_query = expand_query(question, question_type)  # 根据问题类型生成增强后的检索 query。
    return QueryUnderstanding(question_type=question_type, expanded_query=expanded_query, reason=reason)  # 返回结构化理解结果。
